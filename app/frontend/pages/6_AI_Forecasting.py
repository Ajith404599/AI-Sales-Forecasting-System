from datetime import date
import sys
from pathlib import Path

import streamlit as st

frontend_dir = str(Path(__file__).resolve().parents[1])
if frontend_dir not in sys.path:
    sys.path.insert(0, frontend_dir)

from utils.api_client import APIClient, APIError
from utils.page_helpers import setup_authenticated_page
from utils.ui_theme import render_empty_state

user = setup_authenticated_page(
    "AI Sales Forecasting",
    "AI Sales Forecasting",
    "Request a product-level demand forecast from the active, versioned model.",
    "Forecast workspace",
)

try:
    products = APIClient.get_products(active_status=True, limit=200) or []
except Exception as error:
    st.error(f"Could not load the existing product catalog: {error}")
    products = []

try:
    active_model = APIClient.get_active_model()
except Exception as error:
    active_model = None
    st.warning(f"Active model status is unavailable: {error}")

model_col, target_col = st.columns([1.2, 1])
with model_col:
    st.markdown("#### Active model")
    if active_model:
        st.markdown(f"**{active_model['model_name']}** · version `{active_model['model_version']}`")
        st.caption(f"Target: {active_model['prediction_target']} · Trained: {active_model['trained_at']}")
    else:
        render_empty_state("No active model", "An Administrator must complete a successful training run before forecasts are available.")
with target_col:
    st.markdown("#### Forecast target")
    st.caption("Predicted quantity is generated by the saved FastAPI model pipeline and recorded in prediction history.")

st.markdown("#### Forecast inputs")
if not active_model:
    st.info("Forecasting is unavailable until a valid model has been trained.")
elif not products:
    render_empty_state("No active products", "Forecasts use product IDs from the existing Products catalog.")
else:
    product_by_id = {product["product_id"]: product for product in products}
    product_id = st.selectbox(
        "Product",
        list(product_by_id),
        format_func=lambda key: f"{product_by_id[key]['product_name']} · {product_by_id[key]['category']}",
    )
    horizon_mode = st.radio("Forecast input", ["Days ahead", "Specific date"], horizontal=True)
    with st.form("forecast_request_form"):
        if horizon_mode == "Days ahead":
            horizon_days = st.number_input("Forecast horizon", min_value=1, max_value=90, value=7, step=1)
            target_date = None
        else:
            horizon_days = None
            target_date = st.date_input("Forecast date", value=date.today())
        submitted = st.form_submit_button("Generate forecast", type="primary", use_container_width=True)

    if submitted:
        try:
            with st.spinner("Requesting prediction from the active model…"):
                forecast = APIClient.predict_sales(
                    product_id=product_id,
                    horizon_days=horizon_days,
                    forecast_date=target_date.isoformat() if target_date else None,
                )
            st.session_state["latest_forecast"] = forecast
        except APIError as error:
            st.error(error.message)
        except Exception as error:
            st.error(f"Forecast request failed: {error}")

forecast = st.session_state.get("latest_forecast")
if forecast:
    selected_product = next((item for item in products if item["product_id"] == forecast["product_id"]), None)
    st.markdown('<div class="forecast-result">', unsafe_allow_html=True)
    st.markdown("#### Predicted quantity")
    st.markdown(f"<div class='forecast-number'>{float(forecast['predicted_quantity']):,.2f}</div>", unsafe_allow_html=True)
    result_cols = st.columns(4)
    result_cols[0].metric("Product", selected_product["product_name"] if selected_product else f"Product #{forecast['product_id']}")
    result_cols[1].metric("Forecast date", forecast["forecast_date"])
    result_cols[2].metric("Model", forecast["model_name"])
    result_cols[3].metric("Version", forecast["model_version"])
    st.caption(f"Prediction #{forecast['prediction_id']} · Saved {forecast['predicted_at']} · Target: {forecast['prediction_target']}")
    st.markdown('</div>', unsafe_allow_html=True)
